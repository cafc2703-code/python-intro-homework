# Warmup 3: Boolean Expression Practice
# False because not True is False, and False and False is False.
print(not True and False)      
# True because False and False is False, then True or False is True.
print(True or False and False) 
# False because 5 > 3 is True, and not True is False.
print(not (5 > 3))  
 # False because 10 == 10 is True, but 4 != 4 is False.
print(10 == 10 and 4 != 4)     
# True because not False is True and not True is False, so True or False is True.
print(not False or not True)  
